#!/usr/bin/env node
/**
 * Generate the country flag module from `country-flag-icons`.
 *
 * All 265 flags together are ~166KB of markup — small enough to inline, which
 * keeps the single-file share build self-contained. Verified before writing
 * this: none of them use `id`, `<defs>`, `<use>` or `<image>`, so rendering
 * several on one page cannot collide.
 *
 * Re-run after upgrading the package:  node scripts/build-flags.mjs
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'

const SRC = 'node_modules/country-flag-icons/3x2'
const OUT_DIR = 'src/components/flags'
const OUT = join(OUT_DIR, 'index.tsx')

const files = readdirSync(SRC).filter((f) => f.endsWith('.svg')).sort()

const entries = files.map((file) => {
  const code = file.replace('.svg', '')
  const svg = readFileSync(join(SRC, file), 'utf8')
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1]
  if (!viewBox) throw new Error(`${file}: no viewBox`)

  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim()

  // A stray id/defs would break when two flags render together. Verified none
  // exist today; fail loudly rather than ship a silent collision later.
  if (/\sid=|<defs|<use|<image/.test(inner)) {
    throw new Error(`${file}: contains id/defs/use/image — the inline strategy is no longer safe`)
  }

  // Codes are quoted: some are subdivisions like BQ-BO, which is not a bare key.
  return `  ${JSON.stringify(code)}: ['${viewBox}', ${JSON.stringify(inner)}],`
})

mkdirSync(OUT_DIR, { recursive: true })
writeFileSync(
  OUT,
  `/* GENERATED by scripts/build-flags.mjs — do not edit by hand.
   Source: country-flag-icons. Re-run after upgrading that package. */

/** [viewBox, inner markup] per ISO 3166-1 alpha-2 code. */
const FLAGS: Record<string, [string, string]> = {
${entries.join('\n')}
}

interface FlagBase {
  /** ISO 3166-1 alpha-2, case-insensitive. */
  code: string
  className?: string
}

/**
 * Either the flag is labelled or it is explicitly decorative — a union rather
 * than an optional \`title\`, so forgetting the label cannot compile. A flag
 * standing alone is information, and unlabelled it is information only sighted
 * users get.
 *
 * \`decorative\` is for a flag sitting beside the same text it would announce,
 * where labelling it makes a screen reader say everything twice.
 */
export type FlagProps =
  | (FlagBase & { title: string; decorative?: false })
  | (FlagBase & { title?: never; decorative: true })

/**
 * Renders a country flag, or nothing when the code is unknown so a caller can
 * fall back. Markup is generated at build time from a vetted source, which is
 * why setting it directly is safe here.
 */
export function Flag({ code, title, decorative, className }: FlagProps) {
  const entry = FLAGS[code.toUpperCase()]
  if (!entry) return null
  const [viewBox, inner] = entry

  return (
    <svg
      viewBox={viewBox}
      {...(decorative ? { 'aria-hidden': true } : { role: 'img', 'aria-label': title })}
      className={className}
      preserveAspectRatio="xMidYMid slice"
      dangerouslySetInnerHTML={{ __html: inner }}
    />
  )
}

export function hasFlag(code: string) {
  return code.toUpperCase() in FLAGS
}
`,
)

console.log(`✓ generated ${files.length} flags → ${OUT}`)
